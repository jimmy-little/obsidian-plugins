import type { LoadedSkill, SkillInputValues } from "./types";

export const DEEPLINK_TEXT_LIMIT = 9500;

export function buildCorePacket(skill: LoadedSkill, inputs: SkillInputValues): string {
	const inputLines = Object.entries(inputs)
		.filter(([, value]) => value !== undefined && value !== "")
		.map(([key, value]) => {
			const spec = (skill.inputs ?? []).find((item) => item.key === key);
			const label = spec?.label || key;
			return `- **${label}** (\`${key}\`): ${value}`;
		});

	return [
		`# Run: ${skill.label}`,
		"",
		`> Source: ${skill.skillMdPath}`,
		`> Launched: ${new Date().toISOString()}`,
		"",
		"## Instructions",
		"Follow the skill below exactly, using the inputs provided (if any). This packet was",
		"generated by Agent Control Center inside Obsidian. No headless execution happened.",
		"",
		"## Inputs",
		inputLines.length ? inputLines.join("\n") : "_No additional inputs — run with defaults._",
		"",
		"---",
		"",
		`## Skill: ${skill.label}`,
		"",
		skill.body,
		"",
	].join("\n");
}

export function buildDeepLink(promptText: string): {
	url: string | null;
	withinLimit: boolean;
	encodedLength: number;
} {
	const encoded = encodeURIComponent(promptText);
	const withinLimit = encoded.length <= DEEPLINK_TEXT_LIMIT;
	return {
		url: withinLimit ? `cursor://anysphere.cursor-deeplink/prompt?text=${encoded}` : null,
		withinLimit,
		encodedLength: encoded.length,
	};
}

export function buildFileContent(corePacket: string, deepLink: { url: string | null; withinLimit: boolean; encodedLength: number }): string {
	const header = deepLink.withinLimit
		? [
				`> **[Open in Cursor chat](${deepLink.url})**`,
				"> Opens a new Cursor chat with this prompt filled in. Review it, then send.",
				"",
				"---",
				"",
			]
		: [
				`> This packet is ${deepLink.encodedLength.toLocaleString()} characters encoded, over Cursor's`,
				"> 10,000-character link limit. Copy the section below into a new Cursor chat.",
				"",
				"---",
				"",
			];
	return [...header, corePacket].join("\n");
}

export function defaultInputValues(skill: { inputs?: LoadedSkill["inputs"] }): SkillInputValues {
	const values: SkillInputValues = {};
	for (const spec of skill.inputs ?? []) {
		values[spec.key] = spec.default ?? (spec.type === "boolean" ? false : "");
	}
	return values;
}

export function missingRequiredInputs(
	skill: { inputs?: LoadedSkill["inputs"] },
	values: SkillInputValues,
): string[] {
	const missing: string[] = [];
	for (const spec of skill.inputs ?? []) {
		if (!spec.required) continue;
		const value = values[spec.key];
		if (spec.type === "boolean") {
			if (value == null) missing.push(spec.label);
			continue;
		}
		if (String(value ?? "").trim() === "") missing.push(spec.label);
	}
	return missing;
}
